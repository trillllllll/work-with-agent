// Offline compiler for the approved controls-lab v2 snapshot. No runtime editor.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = new URL('../docs/design/dovun/controls-unification/approved-tokens.json', import.meta.url);
const output = new URL('../client/src/styles/control-tokens.css', import.meta.url);
const model = JSON.parse(readFileSync(source, 'utf8'));
if (model.schemaVersion !== 2 || Object.keys(model.themes).sort().join() !== 'dark,light') throw Error('Expected controls-lab v2 light/dark snapshot');
const fonts = { system: '-apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif', rounded: 'ui-rounded, "SF Pro Rounded", system-ui, sans-serif', mono: 'ui-monospace, "SFMono-Regular", Consolas, monospace' };
const rgba = (hex, a) => `rgb(${[1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)).join(' ')} / ${Math.min(1, Math.max(0, a))})`;
const mix = (a, b, p) => `color-mix(in srgb, ${a} ${100 - p}%, ${b})`;
const channels = hex => [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
const blend = (a, b, f) => channels(a).map((v, i) => Math.round(v * (1 - f) + channels(b)[i] * f));
const luminance = rgb => rgb.map(v => v / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4).reduce((sum, v, i) => sum + v * [.2126, .7152, .0722][i], 0);
const contrast = (a, b) => (Math.max(luminance(a), luminance(b)) + .05) / (Math.min(luminance(a), luminance(b)) + .05);
// The demo's dark muted copy falls below 4.5 on the bright edge of its gradient.
// Preserve the approved raw snapshot and minimally raise copy contrast here.
function readable(hex, g) {
  const backgrounds = ['environment', 'panel', 'buttonBg', 'inputBg', 'cardBg', 'overlayBg', 'selectedBg'].flatMap(key => [channels(g[key]), blend(g[key], '#ffffff', g.gradient / 100)]);
  const target = luminance(channels(g.panel)) < .4 ? '#ffffff' : '#000000';
  for (let step = 0; step <= 100; step++) {
    const c = blend(hex, target, step / 100);
    if (backgrounds.every(bg => contrast(c, bg) >= 4.5)) return '#' + c.map(v => v.toString(16).padStart(2, '0')).join('');
  }
  throw Error('No accessible foreground for approved surfaces');
}
const paint = p => `linear-gradient(${p.angle}deg, ${mix(p.background, '#ffffff', p.gradient)}, ${mix(p.background, '#000000', p.gradient * .45)})`;
const shadow = (p, dark, inset = false) => {
  const hi = p.highlight / 100 * (dark ? .13 : .9);
  return inset
    ? `inset ${p.shadowX}px ${p.shadowY}px ${p.shadowBlur}px ${Math.min(0, p.shadowSpread)}px ${rgba(p.shadowColor, p.shadowOpacity / 100)}, 0 1px 0 ${rgba(p.highlightColor, hi * .65)}`
    : `inset 0 1px 0 ${rgba(p.highlightColor, hi)}, inset 0 -1px 0 ${rgba(p.shadowColor, .06)}, ${p.shadowX}px ${p.shadowY}px ${p.shadowBlur}px ${p.shadowSpread}px ${rgba(p.shadowColor, p.shadowOpacity / 100)}`;
};
const focus = (p, dark) => `0 0 0 ${p.focusWidth}px ${rgba(p.focusColor, .85)}, 0 0 0 ${p.focusWidth + 3}px ${rgba(p.focusColor, p.focusOpacity / 100)}, inset 0 1px 0 ${rgba(p.highlightColor, dark ? .1 : .7)}`;
let css = '/* Generated by node scripts/design-tokens.mjs. Edit approved-tokens.json, then regenerate. */\n';
for (const name of ['light', 'dark']) {
  const t = model.themes[name], g = t.global, dark = name === 'dark';
  for (const values of Object.values(t)) for (const [key, v] of Object.entries(values)) {
    if (key === 'fontFamily' ? !Object.hasOwn(fonts, v) : typeof v === 'string' ? !/^#[\da-f]{6}$/i.test(v) : typeof v !== 'number' || !Number.isFinite(v)) throw Error(`Invalid token ${name}/${key}`);
  }
  const vars = {
    'radius': `${g.radius + 9}px`, 'control-font-family': fonts[g.fontFamily], 'control-font-size': `${g.fontSize}px`,
    'control-line-height': g.lineHeight, 'control-duration': `${g.transition}ms`, 'control-disabled-opacity': g.disabledOpacity / 100,
    'background': g.environment, 'foreground': g.text, 'card': g.cardBg, 'card-foreground': g.text,
    'popover': g.overlayBg, 'popover-foreground': g.text, 'primary': g.brand, 'primary-foreground': g.onBrand,
    'secondary': g.buttonBg, 'secondary-foreground': g.text, 'muted': g.inputBg, 'muted-foreground': readable(g.muted, g),
    'link': readable(dark ? g.focusColor : g.brand, g),
    'accent': g.selectedBg, 'accent-foreground': g.text, 'destructive': g.danger, 'destructive-foreground': dark ? g.environment : '#ffffff',
    'border': rgba(g.borderColor, g.borderOpacity / 100), 'input': rgba(g.borderColor, g.borderOpacity / 100), 'ring': g.focusColor,
    'warning': g.warning, 'warning-bg': g.warningBg, 'warning-border': rgba(g.warning, .3),
    'success': g.success, 'success-bg': g.successBg, 'success-border': rgba(g.success, .3),
    'danger-bg': g.dangerBg, 'explore': g.violet, 'explore-bg': g.violetBg, 'explore-border': rgba(g.violet, .3),
    'selected': g.selectedBg, 'sidebar': g.environment,
    'surface-panel': g.panel, 'surface-panel-paint': `linear-gradient(${g.angle}deg, ${mix(g.panel, '#ffffff', g.gradient * .4)}, ${g.panel})`,
    'surface-panel-shadow': `inset 0 1px 0 ${rgba(g.highlightColor, dark ? .09 : .7)}, 0 20px 36px -22px ${rgba(g.shadowColor, g.shadowOpacity / 100 * 1.5)}`,
    'glass-bg': g.cardBg, 'glass-bg-strong': g.overlayBg, 'glass-subtle': rgba(g.highlightColor, dark ? .035 : .32),
    'glass-control': g.inputBg, 'glass-hover': g.selectedBg, 'menu-highlight': g.selectedBg,
    'glass-border': rgba(g.borderColor, g.borderOpacity / 100), 'glass-border-soft': rgba(g.borderColor, g.borderOpacity / 200),
    'glass-highlight': rgba(g.highlightColor, dark ? .13 : .9), 'glass-divider': rgba(g.borderColor, g.borderOpacity / 200),
    'scrollbar-thumb': rgba(g.muted, .3), 'scrollbar-thumb-hover': rgba(g.muted, .5), 'scrollbar-track': 'transparent',
    'workbench-sheet': 'var(--surface-panel-paint)', 'workbench-frame': g.environment,
    'workbench-panel-shadow': 'var(--surface-panel-shadow)', 'workbench-control-shadow': 'var(--surface-input-shadow)',
    'workbench-selected': g.selectedBg, 'workbench-selected-edge': g.brand,
    'workbench-coral': dark ? '#e2a18b' : '#cf7659', 'workbench-muted-coral': dark ? '#392d2c' : '#f6e9e1',
    'overlay-width': `${g.dialogWidth}px`, 'overlay-backdrop': rgba(g.backdropColor, g.backdropOpacity / 100), 'overlay-backdrop-blur': `${g.backdropBlur}px`,
  };
  for (const role of ['button', 'input', 'card', 'overlay']) {
    const p = { ...g, background: g[`${role}Bg`], primaryBg: g.brand, ...t[role] }, prefix = `surface-${role}`;
    Object.assign(vars, {
      [`${prefix}-bg`]: p.background, [`${prefix}-paint`]: paint(p), [`${prefix}-border`]: `${p.borderWidth}px solid ${rgba(p.borderColor, p.borderOpacity / 100)}`,
      [`${prefix}-shadow`]: shadow(p, dark, role === 'input'), [`${prefix}-focus`]: focus(p, dark), [`${prefix}-radius`]: `${p.radius}px`,
      [`${prefix}-text`]: p.text, [`${prefix}-muted`]: readable(p.muted, g), [`${prefix}-font`]: fonts[p.fontFamily],
      [`${prefix}-font-size`]: `${p.fontSize}px`, [`${prefix}-font-weight`]: p.fontWeight, [`${prefix}-line-height`]: p.lineHeight,
      [`${prefix}-padding-x`]: `${p.paddingX}px`, [`${prefix}-padding-y`]: `${p.paddingY}px`, [`${prefix}-gap`]: `${p.gap}px`,
      [`${prefix}-height`]: `${p.height}px`, [`${prefix}-duration`]: `${p.transition}ms`, [`${prefix}-disabled-opacity`]: p.disabledOpacity / 100,
    });
    if (role === 'button') Object.assign(vars, {
      'surface-primary-paint': paint({ ...p, background: p.primaryBg }), 'surface-primary-text': p.onBrand,
      'surface-button-hover-shadow': shadow({ ...p, shadowY: p.shadowY + p.hoverLift + 1 }, dark),
      'surface-button-pressed-shadow': shadow({ ...p, shadowY: 1, shadowBlur: Math.max(2, p.shadowBlur * .5), shadowSpread: 0 }, dark, true),
      'surface-button-hover-brightness': p.hoverBrightness / 100, 'surface-button-hover-offset': `${-p.hoverLift}px`, 'surface-button-pressed-offset': `${p.pressedOffset}px`,
    });
    if (role === 'overlay') Object.assign(vars, { 'overlay-width': `${p.dialogWidth}px`, 'overlay-backdrop': rgba(p.backdropColor, p.backdropOpacity / 100), 'overlay-backdrop-blur': `${p.backdropBlur}px` });
  }
  vars['glass-shadow'] = 'var(--surface-card-shadow)';
  css += `${dark ? '.dark' : ':root'} {\n  color-scheme: ${name};\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;
}
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== css) { console.error('Control tokens drifted. Run node scripts/design-tokens.mjs'); process.exitCode = 1; }
} else { writeFileSync(output, css); console.log(`Generated ${fileURLToPath(output)}`); }
