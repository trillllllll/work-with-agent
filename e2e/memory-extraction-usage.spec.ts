import { randomUUID } from 'node:crypto';
import { test, expect } from './fixtures.js';
import { resetE2eDatabase, e2eDatabase } from './database.js';
const endpoint = process.env.E2E_API_URL ?? 'http://127.0.0.1:3015';
test.beforeEach(resetE2eDatabase);

test('记忆提取记录：真实接口、统计筛选、分页和移动端', async ({ page, request }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const settings = await request.patch(endpoint + '/api/settings', { data: { baseUrl: 'http://127.0.0.1:4010/v1', model: 'mock-model', apiKey: 'e2e-key' } });
  expect(settings.ok()).toBe(true);
  const created = await request.post(endpoint + '/api/topics', { data: { name: '用量验收' } });
  const topicId = (await created.json()).data.id as string;
  expect((await request.post(endpoint + '/api/tasks', { data: { title: '采用 SQLite 保存数据', topicId } })).ok()).toBe(true);
  const run = await request.post(endpoint + '/api/v1/knowledge/auto-memory/run', { data: { topicId, requestId: randomUUID() } });
  expect(run.ok(), await run.text()).toBe(true);
  const result = await run.json();
  expect(result.data.job.status).toBe('proposed');
  const stats = await request.get(endpoint + '/api/v1/knowledge/auto-memory/jobs?topicId=' + topicId);
  const data = (await stats.json()).data;
  expect(data.items[0]).toMatchObject({ requestedModel: 'mock-model', responseModel: 'mock-model-actual', provider: '127.0.0.1', inputTokens: 120, outputTokens: 30, totalTokens: 150 });
  expect(await e2eDatabase.memory.count()).toBe(0);
  for (let i = 0; i < 22; i++) await e2eDatabase.autoMemoryJob.create({ data: { scopeKey: 'topic:' + topicId, inputHash: 'history-' + i, status: 'failed', snapshot: '{}', errorCode: 'INVALID_MODEL_OUTPUT', errorMessage: 'summary: invalid_type', createdAt: new Date(Date.now() - 1000 * (i + 1)).toISOString() } });
  await page.goto('/#/knowledge/memories?topicId=' + topicId);
  await page.getByRole('button', { name: '提取记录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '提取记录', exact: true })).toBeVisible();
  const summary = page.getByLabel('筛选范围用量汇总');
  await expect(summary).toContainText('23');
  await expect(summary).toContainText('150');
  await expect(page.getByText('历史用量未知').filter({ visible: true }).first()).toBeVisible();
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(page.getByText('共 23 条 · 第 2 页')).toBeVisible();
  await expect(summary).toContainText('150');
  await page.getByLabel('筛选模型').selectOption('mock-model');
  await expect(page.getByText('共 1 条 · 第 1 页')).toBeVisible();
  await expect(page.getByText('mock-model-actual', { exact: false }).filter({ visible: true }).first()).toBeVisible();
  await page.getByLabel('筛选提供商').selectOption('127.0.0.1');
  await expect(page.getByText('共 1 条 · 第 1 页')).toBeVisible();
  await page.getByLabel('所属清单', { exact: true }).selectOption('all');
  await expect(page).toHaveURL(/topicId=all/);
  await expect(page.getByText('共 1 条 · 第 1 页')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: '提取记录', exact: true })).toBeVisible();
  await expect(page.getByLabel('所属清单', { exact: true })).toHaveValue('all');
  await page.getByLabel('筛选模型').selectOption('mock-model');
  await expect(page.getByText('共 1 条 · 第 1 页')).toBeVisible();
  if (testInfo.project.name === 'chromium') {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: '/tmp/wwa-memory-1440-light.png', fullPage: true });
    await page.getByRole('button', { name: '切换主题', exact: true }).click();
    await page.getByRole('menuitem', { name: '深色', exact: true }).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await expect(page.getByLabel('开始日期', { exact: true })).toHaveCSS('color', 'rgb(230, 233, 236)');
    await page.screenshot({ path: '/tmp/wwa-memory-1440-dark.png', fullPage: true, animations: 'disabled' });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.memory-jobs-cards')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator('.memory-jobs-cards').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/wwa-memory-390-' + testInfo.project.name + '.png', fullPage: true });
  await page.getByRole('button', { name: '返回长期记忆', exact: true }).click();
  await expect(page).toHaveURL(/knowledge\/memories\?topicId=inbox/);
  await page.goBack();
  await expect(page.getByRole('heading', { name: '提取记录', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('提取返回无用量时显示未知且读取失败可重试', async ({ page, request }) => {
  expect((await request.patch(endpoint + '/api/settings', { data: { baseUrl: 'http://127.0.0.1:4010/v1', model: 'mock-no-usage', apiKey: 'e2e-key' } })).ok()).toBe(true);
  expect((await request.post(endpoint + '/api/tasks', { data: { title: '无用量测试' } })).ok()).toBe(true);
  await request.post(endpoint + '/api/v1/knowledge/auto-memory/run', { data: { topicId: null, requestId: randomUUID() } });
  await page.goto('/#/knowledge/extractions?topicId=inbox');
  await expect(page.getByText('接口未返回用量').filter({ visible: true }).first()).toBeVisible();
  await expect(page.getByLabel('筛选范围用量汇总')).toContainText('未知');
  await page.route('**/api/v1/knowledge/auto-memory/jobs?**', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ data: null, error: '模拟读取失败' }) }));
  await page.getByRole('button', { name: '刷新记录', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: '提取记录读取失败' })).toBeVisible({ timeout: 15000 });
  await page.unroute('**/api/v1/knowledge/auto-memory/jobs?**');
  await page.getByRole('button', { name: '重试读取', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: '提取记录读取失败' })).toHaveCount(0);
});
